"""Noether ↔ PINNeAPPle data bridge.

Provides two adapters:

NoetherDatasetBridge
    Wraps a ``noether.data.base.Dataset`` (or any mapping-style dataset
    that yields ``{field: tensor}`` dicts) so it can be used as a standard
    ``torch.utils.data.Dataset`` inside PINNeAPPle's training loops.

PhysicalSampleDataset
    Converts a list of PINNeAPPle ``PhysicalSample`` (UPD format) objects
    into a Noether-compatible ``{field: tensor}`` dataset, enabling the full
    Noether training pipeline (``WeightedLossTrainer``, ``noether-train``)
    to consume data generated by PINNeAPPle's simulation modules.

Workflow examples
-----------------
# 1. Feed Noether built-in dataset to PINNeAPPle Trainer
>>> from noether.data.datasets import DrivAerMLDataset
>>> from pinneaple_data.noether_dataset import NoetherDatasetBridge
>>> noether_ds = DrivAerMLDataset(root="/data/driveaerml")
>>> bridge = NoetherDatasetBridge(noether_ds, target_fields=["pressure", "velocity"])
>>> # Use bridge with any PINNeAPPle DataLoader

# 2. Feed PINNeAPPle simulation data to NoetherSurrogateTrainer
>>> from pinneaple_data.noether_dataset import PhysicalSampleDataset
>>> samples = [...]  # list of PhysicalSample from MuJoCoRunner / GenesisRunner / FEniCS
>>> ds = PhysicalSampleDataset(samples, input_fields=["qpos","qvel"], output_fields=["xpos"])
>>> loader = torch.utils.data.DataLoader(ds, batch_size=8, shuffle=True)
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional, Sequence

import numpy as np
import torch
from torch.utils.data import Dataset as TorchDataset


# ---------------------------------------------------------------------------
# NoetherDatasetBridge — wrap a noether dataset as a plain PyTorch Dataset
# ---------------------------------------------------------------------------

class NoetherDatasetBridge(TorchDataset):
    """Bridge a ``noether.data.base.Dataset`` to a plain PyTorch Dataset.

    Makes Noether's built-in datasets (DrivAerML, AhmedML, SIMSHIFT, etc.)
    usable in PINNeAPPle training loops without any Hydra/config machinery.

    Parameters
    ----------
    noether_dataset : a Noether Dataset instance
    input_fields : field names to expose as model inputs.
        If None, all non-target fields are treated as inputs.
    target_fields : field names to expose as targets (suffixed with ``_target``
        in the output dict for consistency with ``NoetherSurrogateTrainer``).
        If None, no target separation is applied.
    transform : optional callable applied to each sample dict after retrieval.
    device : move tensors to this device. None = keep on CPU.
    """

    def __init__(
        self,
        noether_dataset,
        input_fields: Optional[List[str]] = None,
        target_fields: Optional[List[str]] = None,
        transform=None,
        device: Optional[str] = None,
    ) -> None:
        self._ds = noether_dataset
        self.input_fields = input_fields
        self.target_fields = target_fields or []
        self.transform = transform
        self.device = torch.device(device) if device else None

    def __len__(self) -> int:
        return len(self._ds)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        raw = self._ds[idx]
        if not isinstance(raw, dict):
            raw = {"y": raw}

        out: Dict[str, torch.Tensor] = {}
        for k, v in raw.items():
            t = torch.as_tensor(np.asarray(v), dtype=torch.float32)
            if self.device is not None:
                t = t.to(self.device)
            if k in self.target_fields:
                out[f"{k}_target"] = t
            else:
                out[k] = t

        if self.transform is not None:
            out = self.transform(out)
        return out


# ---------------------------------------------------------------------------
# PhysicalSampleDataset — convert PINNeAPPle PhysicalSamples to Noether format
# ---------------------------------------------------------------------------

class PhysicalSampleDataset(TorchDataset):
    """Convert a list of PINNeAPPle ``PhysicalSample`` (UPD) to a
    Noether-compatible ``{field: tensor}`` PyTorch Dataset.

    Each sample in the list becomes one dataset item. Fields from
    ``PhysicalSample.fields`` are exposed; coordinate arrays from
    ``PhysicalSample.coords`` are optionally included.

    Parameters
    ----------
    samples : list of PhysicalSample
    input_fields : field names from ``PhysicalSample.fields`` to use as
        model inputs. If None, all fields except output_fields are used.
    output_fields : field names used as supervision targets (suffixed with
        ``_target`` in the output dict).
    include_coords : if True, include coordinate arrays as extra input fields.
    transform : optional callable applied to each sample dict.
    """

    def __init__(
        self,
        samples: Sequence,
        input_fields: Optional[List[str]] = None,
        output_fields: Optional[List[str]] = None,
        include_coords: bool = False,
        transform=None,
    ) -> None:
        self.samples = list(samples)
        self.input_fields = input_fields
        self.output_fields = output_fields or []
        self.include_coords = include_coords
        self.transform = transform

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        sample = self.samples[idx]
        fields: Dict[str, Any] = {}

        # Fields
        for k, v in sample.fields.items():
            t = torch.as_tensor(np.asarray(v), dtype=torch.float32)
            if k in self.output_fields:
                fields[f"{k}_target"] = t
            elif self.input_fields is None or k in self.input_fields:
                fields[k] = t

        # Coordinates
        if self.include_coords:
            for k, v in sample.coords.items():
                t = torch.as_tensor(np.asarray(v), dtype=torch.float32)
                fields[f"coord_{k}"] = t

        if self.transform is not None:
            fields = self.transform(fields)
        return fields

    @classmethod
    def from_upd_list(
        cls,
        samples: Sequence,
        input_fields: Optional[List[str]] = None,
        output_fields: Optional[List[str]] = None,
        include_coords: bool = False,
    ) -> "PhysicalSampleDataset":
        """Convenience constructor — alias for the standard ``__init__``."""
        return cls(
            samples=samples,
            input_fields=input_fields,
            output_fields=output_fields,
            include_coords=include_coords,
        )


# ---------------------------------------------------------------------------
# Utility: build a train/val split from a list of PhysicalSamples
# ---------------------------------------------------------------------------

def split_physical_samples(
    samples: Sequence,
    val_fraction: float = 0.1,
    seed: int = 42,
    **dataset_kwargs,
) -> tuple["PhysicalSampleDataset", "PhysicalSampleDataset"]:
    """Split a list of PhysicalSamples into train and validation datasets.

    Parameters
    ----------
    samples : full list of PhysicalSample
    val_fraction : fraction reserved for validation (0 < val_fraction < 1)
    seed : random seed for reproducibility
    **dataset_kwargs : forwarded to ``PhysicalSampleDataset``

    Returns
    -------
    (train_dataset, val_dataset)
    """
    import random
    rng = random.Random(seed)
    idx = list(range(len(samples)))
    rng.shuffle(idx)
    n_val = max(1, int(len(samples) * val_fraction))
    val_idx = idx[:n_val]
    train_idx = idx[n_val:]
    train_samples = [samples[i] for i in train_idx]
    val_samples = [samples[i] for i in val_idx]
    return (
        PhysicalSampleDataset(train_samples, **dataset_kwargs),
        PhysicalSampleDataset(val_samples, **dataset_kwargs),
    )
